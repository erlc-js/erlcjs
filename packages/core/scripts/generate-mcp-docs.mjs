import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const coreRoot = path.resolve(here, '..');
const repoRoot = path.resolve(coreRoot, '..', '..');
const docsRoot = path.join(repoRoot, 'apps', 'docs', 'src', 'content', 'docs');
const generatedFile = path.join(coreRoot, 'src', 'cli', 'generated.ts');
const corePackage = JSON.parse(fs.readFileSync(path.join(coreRoot, 'package.json'), 'utf8'));

if (!fs.existsSync(docsRoot)) {
  if (fs.existsSync(generatedFile)) {
    console.log('docs source not found; keeping the existing generated MCP index');
    process.exit(0);
  }
  throw new Error(`docs source not found: ${docsRoot}`);
}

function walk(directory, out = []) {
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    const full = path.join(directory, entry.name);
    if (entry.isDirectory()) walk(full, out);
    else if (entry.name.endsWith('.md')) out.push(full);
  }
  return out;
}

function parseFrontmatter(source) {
  if (!source.startsWith('---')) return { data: {}, body: source };

  const end = source.indexOf('\n---', 3);
  if (end === -1) return { data: {}, body: source };

  const raw = source.slice(3, end).trim();
  const data = {};

  for (const line of raw.split(/\r?\n/)) {
    const match = line.match(/^([A-Za-z0-9_-]+):\s*(.*)$/);
    if (!match) continue;

    let value = match[2].trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    data[match[1]] = value;
  }

  return {
    data,
    body: source
      .slice(end + 4)
      .replace(/^\s*\r?\n/, '')
      .trim(),
  };
}

function stripMarkdown(value) {
  return value
    .replace(/```[\s\S]*?```/g, ' ')
    .replace(/`([^`]+)`/g, '$1')
    .replace(/!\[[^\]]*\]\([^)]*\)/g, ' ')
    .replace(/\[([^\]]+)\]\([^)]*\)/g, '$1')
    .replace(/<[^>]+>/g, ' ')
    .replace(/[*_~#>|]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

function fallbackDescription(body) {
  const rows = body.split(/\r?\n/);
  const paragraph = [];

  for (const row of rows) {
    const line = row.trim();
    if (!line) {
      if (paragraph.length > 0) break;
      continue;
    }
    if (
      line.startsWith('#') ||
      line.startsWith('```') ||
      line.startsWith(':::') ||
      line.startsWith('|') ||
      line.startsWith('-') ||
      line.startsWith('*')
    ) {
      if (paragraph.length > 0) break;
      continue;
    }
    paragraph.push(line);
  }

  return stripMarkdown(paragraph.join(' ')).slice(0, 220);
}

function routeFor(relativePath) {
  const withoutExtension = relativePath.replace(/\\/g, '/').replace(/\.md$/, '');
  if (withoutExtension === 'index') {
    return { slug: 'index', path: '/docs/' };
  }
  if (withoutExtension.endsWith('/index')) {
    const slug = withoutExtension.slice(0, -6);
    return { slug, path: `/docs/${slug}/` };
  }
  return { slug: withoutExtension, path: `/docs/${withoutExtension}/` };
}

function sectionFor(slug) {
  if (slug === 'index') return 'overview';
  return slug.split('/')[0] || 'overview';
}

const docs = walk(docsRoot)
  .map((file) => {
    const relative = path.relative(docsRoot, file);
    const { slug, path: routePath } = routeFor(relative);
    const source = fs.readFileSync(file, 'utf8');
    const { data, body } = parseFrontmatter(source);
    const title = data.title || path.basename(relative, '.md');
    const description = data.description || fallbackDescription(body);

    return {
      slug,
      path: routePath,
      title,
      description,
      section: sectionFor(slug),
      order: Number(data.order) || 0,
      content: body,
    };
  })
  .sort((a, b) => {
    const sectionOrder = { overview: 0, guides: 1, api: 2 };
    const sectionA = sectionOrder[a.section] ?? 3;
    const sectionB = sectionOrder[b.section] ?? 3;
    return sectionA - sectionB || a.order - b.order || a.title.localeCompare(b.title);
  });

fs.mkdirSync(path.dirname(generatedFile), { recursive: true });
fs.writeFileSync(
  generatedFile,
  `// Generated by scripts/generate-mcp-docs.mjs. Do not edit.\n` +
    `import type { BundledDoc } from './types.js';\n\n` +
    `export const PACKAGE_VERSION = ${JSON.stringify(corePackage.version)};\n\n` +
    `export const DOCS: BundledDoc[] = ${JSON.stringify(docs, null, 2)};\n`,
  'utf8',
);

console.log(`wrote ${docs.length} docs to ${path.relative(repoRoot, generatedFile)}`);
